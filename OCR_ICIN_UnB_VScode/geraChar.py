def gchar_ruido(P, Ruido):
    rng = np.random.default_rng()
    Pn = P.copy()
    BitsRuido = int(np.ceil(63 * Ruido / 100))

    if BitsRuido == 0:
        return Pn

    for i in range(Pn.shape[0]):
        indices_para_inverter = rng.choice(63, size=BitsRuido, replace=False)
        for idx in indices_para_inverter:
            Pn[i, idx] = 1 - Pn[i, idx]

    return Pn

def showChar(P):
    import matplotlib.pyplot as plt
    import matplotlib.cm as cm
    Pc = 1 - P
    plt.figure(figsize=(10, 4))
    for i in range(16):
        plt.subplot(2, 8, i + 1)
        plt.imshow(Pc[i, :].reshape(9, 7), cmap=cm.Greys, interpolation='none')
        plt.axis('off')
    plt.show()
    return



def validacao(Pn, net):
    m = []
    idx = []
    predictions = net.predict(Pn, verbose=0)
    for k in range(16):
       p = predictions[k,:]
       m.append(np.max(p))
       idx.append(np.argmax(p))

    bincor = 0
    for i in range(16):
        if idx[i] != i:
            bincor += 1

    return (bincor, idx)